import { CheckCircle2, CircleDashed, OctagonAlert, TriangleAlert } from "lucide-react";

import { CheckBadge } from "@/components/invoices/status-badges";
import { Card, CardBody } from "@/components/ui/card";
import { DECISION_META } from "@/lib/status";
import { cn } from "@/lib/utils";
import type { Decision, ValidationResult } from "@/types/api";

const BANNER = {
  APPROVED: { box: "border-success-ring bg-success-soft", text: "text-success", Icon: CheckCircle2 },
  NEEDS_REVIEW: { box: "border-warning-ring bg-warning-soft", text: "text-warning", Icon: TriangleAlert },
  REJECTED: { box: "border-danger-ring bg-danger-soft", text: "text-danger", Icon: OctagonAlert },
} as const;

export function DecisionPanel({ decision }: { decision: Decision | null }) {
  if (!decision) return null;
  const style = BANNER[decision.status];
  const problems = decision.reasons.filter((r) => r.severity !== "INFO");
  const passes = decision.reasons.filter((r) => r.severity === "INFO");
  return (
    <div className={cn("rounded-lg border p-5", style.box)} data-testid="decision-panel">
      <div className="flex items-center gap-3">
        <style.Icon className={cn("h-7 w-7", style.text)} />
        <div>
          <p className="text-[11px] font-medium uppercase tracking-wider text-slate-500">Decision</p>
          <p className={cn("text-xl font-semibold tracking-tight", style.text)}>
            {DECISION_META[decision.status].label.toUpperCase()}
          </p>
        </div>
      </div>
      {problems.length > 0 ? (
        <div className="mt-4">
          <p className="mb-1.5 text-[13px] font-medium text-slate-700">Reasons</p>
          <ul className="space-y-1.5">
            {problems.map((reason, i) => (
              <li key={`${reason.code}-${i}`} className="flex gap-2 text-sm text-slate-800">
                <span className={cn("mt-2 h-1.5 w-1.5 shrink-0 rounded-full", reason.severity === "BLOCKING" ? "bg-danger" : "bg-amber-500")} />
                {reason.message}
              </li>
            ))}
          </ul>
        </div>
      ) : (
        <p className="mt-3 text-sm text-slate-700">All verification checks passed.</p>
      )}
      {passes.length > 0 && (
        <details className="mt-4 text-[13px] text-slate-600">
          <summary className="cursor-pointer select-none font-medium">{passes.length} checks passed</summary>
          <ul className="mt-2 space-y-1">
            {passes.map((reason, i) => (
              <li key={`${reason.code}-${i}`} className="flex gap-2">
                <CheckCircle2 className="mt-0.5 h-3.5 w-3.5 shrink-0 text-success" />
                {reason.message}
              </li>
            ))}
          </ul>
        </details>
      )}
      <p className="mt-4 text-[11px] text-slate-500">
        Generated by deterministic business rules from the validation results — not by AI.
      </p>
    </div>
  );
}

const ICON = {
  PASSED: <CheckCircle2 className="h-4 w-4 text-success" />,
  WARNING: <TriangleAlert className="h-4 w-4 text-amber-500" />,
  FAILED: <OctagonAlert className="h-4 w-4 text-danger" />,
  SKIPPED: <CircleDashed className="h-4 w-4 text-slate-400" />,
} as const;

const GROUPS: { title: string; prefixes: string[] }[] = [
  { title: "Document data", prefixes: ["REQUIRED_FIELDS", "INVOICE_DATE", "CURRENCY_SUPPORTED", "AMOUNTS_VALID", "LINE_ITEMS_VALID", "EXTRACTION_QUALITY"] },
  { title: "Financial checks", prefixes: ["TOTAL_ARITHMETIC", "LINE_ITEM_MATH", "LINE_ITEMS_SUM"] },
  { title: "Vendor verification", prefixes: ["VENDOR_MATCH", "VENDOR_STATUS", "VENDOR_GSTIN"] },
  { title: "Purchase order", prefixes: ["PO_EXISTS", "PO_VENDOR", "PO_STATUS", "PO_CURRENCY", "PO_BALANCE", "PO_LINE_ITEMS"] },
  { title: "Duplicate detection", prefixes: ["DUP_FILE", "DUP_BUSINESS", "DUP_POTENTIAL"] },
];

export function ValidationList({ validations }: { validations: ValidationResult[] }) {
  if (validations.length === 0)
    return <p className="p-5 text-sm text-muted-foreground">No validation results yet.</p>;
  return (
    <div className="space-y-4">
      {GROUPS.map((group) => {
        const items = group.prefixes
          .map((code) => validations.find((v) => v.validation_type === code))
          .filter((v): v is ValidationResult => !!v);
        if (items.length === 0) return null;
        return (
          <Card key={group.title}>
            <div className="border-b px-5 py-3 text-[13px] font-semibold">{group.title}</div>
            <CardBody className="divide-y p-0">
              {items.map((v) => (
                <div key={v.validation_type} className="flex gap-3 px-5 py-3.5" data-testid={`validation-${v.validation_type}`}>
                  <div className="mt-0.5">{ICON[v.status]}</div>
                  <div className="min-w-0 flex-1">
                    <div className="flex flex-wrap items-center justify-between gap-2">
                      <p className="text-sm font-medium">{v.label}</p>
                      <CheckBadge status={v.status} />
                    </div>
                    <p className="mt-0.5 text-[13px] text-slate-600">{v.message}</p>
                    {(v.expected_value || v.actual_value) && (
                      <dl className="mt-2 flex flex-wrap gap-x-6 gap-y-1 text-xs">
                        {v.expected_value && (
                          <div className="flex gap-1.5">
                            <dt className="text-muted-foreground">Expected</dt>
                            <dd className="tabular font-medium">{v.expected_value}</dd>
                          </div>
                        )}
                        {v.actual_value && (
                          <div className="flex gap-1.5">
                            <dt className="text-muted-foreground">Actual</dt>
                            <dd className="tabular font-medium">{v.actual_value}</dd>
                          </div>
                        )}
                      </dl>
                    )}
                  </div>
                </div>
              ))}
            </CardBody>
          </Card>
        );
      })}
    </div>
  );
}

