IST = timezone(timedelta(hours=5, minutes=30))
UPLOADER = "clerk@payflow.demo"


def rebuild() -> None:
    """Drop every table in the database and recreate the schema through Alembic migrations."""
    from alembic import command
    from alembic.config import Config

    engine = get_engine()
    meta = MetaData()
    meta.reflect(bind=engine)
    with engine.begin() as conn:
        for table in reversed(meta.sorted_tables):
            conn.execute(text(f'DROP TABLE IF EXISTS "{table.name}" CASCADE'))
    print(f"Dropped {len(meta.tables)} tables")
    cfg = Config(str(ROOT / "backend" / "alembic.ini"))
    cfg.set_main_option("script_location", str(ROOT / "backend" / "migrations"))
    command.upgrade(cfg, "head")
    print("Schema migrated to head")


def seed_vendors(db) -> dict[str, Vendor]:
    vendors: dict[str, Vendor] = {}
    for row in json.loads((DATA / "vendors" / "vendors.json").read_text(encoding="utf-8")):
        vendor = db.scalar(select(Vendor).where(Vendor.vendor_code == row["vendor_code"]))
        if vendor is None:
            vendor = Vendor(vendor_code=row["vendor_code"], is_demo=True)
            db.add(vendor)
        vendor.vendor_name = row["vendor_name"]
        vendor.normalized_name = normalize_vendor_name(row["vendor_name"])
        vendor.gstin, vendor.address = row["gstin"], row["address"]
        vendor.email, vendor.phone, vendor.status = row["email"], row["phone"], row["status"]
        vendor.bank_account_number = row.get("bank_account_number")
        vendor.bank_ifsc = row.get("bank_ifsc")
        vendors[row["vendor_code"]] = vendor
    db.commit()
    return vendors


def seed_purchase_orders(db, vendors: dict[str, Vendor]) -> None:
    for row in json.loads((DATA / "purchase_orders" / "purchase_orders.json").read_text(encoding="utf-8")):
        if db.scalar(select(PurchaseOrder).where(PurchaseOrder.po_number == row["po_number"])):
            continue
        po = PurchaseOrder(
            po_number=row["po_number"], vendor_id=vendors[row["vendor_code"]].id,
            po_date=date.fromisoformat(row["po_date"]), currency=row["currency"],
            total_amount=Decimal(row["total_amount"]), status=row["status"],
            description=row["description"], is_demo=True,
        )  # fmt: skip
        for item in row["items"]:
            qty, price = Decimal(str(item["quantity"])), Decimal(str(item["unit_price"]))
            po.items.append(
                PurchaseOrderItem(description=item["description"], quantity=qty, unit_price=price,
                                  total_amount=qty * price)  # fmt: skip
            )
        db.add(po)
    db.commit()


def _uploaded_at(invoice_date: str, rng: random.Random) -> datetime:
    """Invoices reach AP 1-3 working days after they are dated, during office hours (IST)."""
    day = date.fromisoformat(invoice_date) + timedelta(days=rng.randint(1, 3))
    local = datetime.combine(day, time(rng.randint(9, 17), rng.randint(0, 59)), IST)
    return min(local, datetime.now(IST) - timedelta(hours=2)).astimezone(UTC)


def seed_history(db, storage) -> int:
    settings = get_settings()
    history = json.loads((DATA / "invoices" / "history" / "history.json").read_text(encoding="utf-8"))
    rng = random.Random(42)
    created = 0
    for row in sorted(history, key=lambda r: r["order"]):
        if db.scalar(select(Invoice).where(Invoice.original_file_name == row["file"])):
            continue
        pdf = (DATA / "invoices" / "history" / row["file"]).read_bytes()
        invoice, run = create_invoice_from_upload(
            db, settings, storage, filename=row["file"], content_type="application/pdf",
            data=pdf, uploaded_by=UPLOADER,
        )  # fmt: skip
        uploaded_at = _uploaded_at(row["invoice_date"], rng)
        invoice.uploaded_at = uploaded_at
        invoice.source_origin = "SEED_HISTORY"  # reference history: never removed by "Reset demo"
        document = pdf_extractor.extract_text(pdf)
        invoice.extracted_text, invoice.extraction_method = document.text, "TEXT"
        invoice.page_count = document.page_count
        extracted = ExtractedInvoice(
            vendor_name=row["vendor"], vendor_address=row.get("vendor_address"), vendor_gstin=row["gstin"],
            invoice_number=row["invoice_number"], invoice_date=row["invoice_date"], due_date=row["due_date"],
            purchase_order_number=row["po_number"], bank_account_details=row.get("bank_details"),
            currency=row["currency"], subtotal=row["subtotal"], tax_amount=row["tax"], total_amount=row["total"],
            payment_terms="30 days",
            line_items=[ExtractedLineItem(**i) for i in row["items"]],
        )  # fmt: skip
        pipeline.apply_extraction(db, invoice, extracted)
        # Click-to-highlight evidence: where each extracted value is printed on the PDF.
        invoice.visual_evidence = build_invoice_visual_evidence(invoice.extracted_data, extract_pdf_layout(pdf))
        db.commit()

        ctx = pipeline.PipelineContext(db, settings, storage, llm=None)  # type: ignore[arg-type]
        run_service.claim_run(db, run.id)
        live = pipeline.load_active_run(db, run.id)
        for stage in (Stage.DOCUMENT_EXTRACTION, Stage.AI_EXTRACTION):
            run_service.begin_stage(db, live, stage)
            run_service.finish_stage(db, live, stage, StageStatus.COMPLETED, "Loaded from previously extracted data.")
        db.commit()
        pipeline.stage_validate(ctx, live, "data")
        pipeline.stage_vendor_check(ctx, live)
        pipeline.stage_po_match(ctx, live)
        pipeline.stage_duplicate_check(ctx, live)
        pipeline.stage_validate(ctx, live, "financial")
        pipeline.stage_decision(ctx, live)
        db.refresh(invoice)
        auto = invoice.decision_status
        if auto != row["expected_outcome"]:
            raise SystemExit(f"{row['file']}: pipeline decided {auto}, catalogue expects {row['expected_outcome']}")

        resolved = None
        if row.get("resolve"):
            action, comment, actor = row["resolve"]
            review = db.scalar(select(Review).where(Review.invoice_id == invoice.id))
            review_service.apply_review_decision(db, review.id, ReviewAction(action), comment, user_id=actor, settings=settings)
            db.refresh(invoice)
            resolved = invoice.decision_status
        _backdate(db, invoice, run.id, uploaded_at, rng)
        created += 1
        tail = f" -> reviewer: {resolved}" if resolved else ""
        print(f"  {row['invoice_number']:<20} {row['vendor'][:34]:<34} {auto}{tail}")
    return created


def _backdate(db, invoice: Invoice, run_id, uploaded_at: datetime, rng: random.Random) -> None:
    """Make run, stage, audit and review timestamps consistent with the historical upload date."""
    run = db.get(ProcessingRun, run_id)
    duration = rng.randint(14, 48)
    run.started_at = uploaded_at
    run.completed_at = uploaded_at + timedelta(seconds=duration)
    for index, event in enumerate(sorted(run.stage_events, key=lambda e: e.started_at or uploaded_at)):
        event.started_at = uploaded_at + timedelta(seconds=index * duration // 9)
        event.completed_at = uploaded_at + timedelta(seconds=(index + 1) * duration // 9)
    decided = uploaded_at + timedelta(hours=rng.randint(3, 30))
    for check in db.scalars(select(ValidationResult).where(ValidationResult.invoice_id == invoice.id)):
        check.created_at = uploaded_at + timedelta(seconds=duration)
    decisions = db.scalars(select(Decision).where(Decision.invoice_id == invoice.id).order_by(Decision.created_at)).all()
    for index, row in enumerate(decisions):  # first = automated decision, later ones = the reviewer's
        row.created_at = uploaded_at + timedelta(seconds=duration) if index == 0 else decided
    for log in db.scalars(select(AuditLog).where(AuditLog.invoice_id == invoice.id)):
        human = log.actor_type == "USER"
        log.created_at = decided if human else uploaded_at + timedelta(seconds=duration)
    review = db.scalar(select(Review).where(Review.invoice_id == invoice.id))
    if review:
        review.created_at = uploaded_at + timedelta(seconds=duration)
        review.updated_at = decided if review.final_action else review.created_at
    db.commit()


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--rebuild", action="store_true", help="backup, drop all tables, migrate, then seed")
    parser.add_argument("--no-backup", action="store_true", help="skip the JSON backup before --rebuild")
    parser.add_argument("--no-history", action="store_true", help="only seed users, vendors and purchase orders")
    args = parser.parse_args()

    settings = get_settings()
    print(f"Database: {settings.database_url.split('@')[-1]}   Storage: {settings.storage_backend}")
    if args.rebuild:
        if not args.no_backup:
            from backup_database import backup

            backup()
        rebuild()
    storage = get_storage(settings)
    with get_session_factory()() as db:
        print(f"Demo users created: {ensure_demo_accounts(db)}")
        vendors = seed_vendors(db)
        seed_purchase_orders(db, vendors)
        print(f"Vendors: {len(vendors)}  POs: {db.query(PurchaseOrder).count()}")
        if not args.no_history:
            print(f"History invoices seeded: {seed_history(db, storage)}")


if __name__ == "__main__":
    sys.path.insert(0, str(Path(__file__).parent))
    main()
