"""Seed the database (Supabase Postgres in production) with the PayFlow AI dataset.

    python scripts/seed_database.py               # idempotent: users, vendors, POs, history
    python scripts/seed_database.py --rebuild     # backup -> drop every table -> migrate -> seed

What gets seeded (all from sample_data/, generated by generate_sample_invoices.py):
* demo users (one per role), vendors with verified bank details, purchase orders;
* 50 HISTORY invoices = "previously extracted" invoices. Their extracted fields come from
  history.json (no LLM calls) and they are pushed through the *real* deterministic pipeline
  (validation -> vendor -> PO -> duplicates -> decision), so PO balances, allocations, audit logs
  and dashboards are produced by the same code that handles live uploads. Reviews a human
  resolved at the time are resolved again with the recorded comment. The PDFs are uploaded to the
  configured storage (Supabase bucket) so they can be opened in the app.

History invoices are marked source_origin=SEED_HISTORY. The "Reset demo" button only deletes
LIVE_UPLOAD invoices (the 15 test PDFs), so this seed is never disturbed by a reset.
"""

